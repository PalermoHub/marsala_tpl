import sys, pandas as pd
D=sys.argv[1]
rd=lambda n: pd.read_csv(f"{D}/{n}.txt",dtype=str,keep_default_na=False)
stops,trips,st,routes=rd("stops"),rd("trips"),rd("stop_times"),rd("routes")
hms=lambda s:(lambda a:int(a[0])*3600+int(a[1])*60+int(a[2]))(s.split(":"))
st["seq"]=st.stop_sequence.astype(int); st=st.sort_values(["trip_id","seq"])
st["t"]=st.arrival_time.map(hms); st["sd"]=st.shape_dist_traveled.astype(float)
g=st.groupby("trip_id")
tr=pd.DataFrame({"n":g.size(),"dur":g.t.max()-g.t.min(),"len":g.sd.max()-g.sd.min()})
tr["kmh"]=tr.len/tr.dur*3.6
tr=tr.join(trips.set_index("trip_id")[["route_id","service_id"]]).join(routes.set_index("route_id").route_short_name,on="route_id")
tr["fam"]=tr.index.str.replace(r"\d+","#",regex=True).str.replace(r"#_[A-Z]_#_#","FORMATO_A",regex=True)
print("VELOCITÀ MEDIA PER CORSA (shape_dist/durata) p5/p50/p95:",tr.kmh.quantile([.05,.5,.95]).round(1).tolist())
print(tr.groupby("route_short_name").kmh.agg(["count","min","median","max"]).round(1).to_string())
st["same"]=(g.t.diff()==0)
print("\nfermate con orario identico alla precedente, per famiglia di trip_id:")
st=st.join(tr.fam,on="trip_id")
print(st.groupby("fam").same.agg(["sum","count"]).assign(pct=lambda d:(100*d["sum"]/d["count"]).round(1)).to_string())
# quante corse hanno ogni fermata con orario multiplo di 60 s (risoluzione al minuto)?
st["min_res"]=(st.t%60==0)
print("\nquota di orari al minuto esatto, per famiglia:",st.groupby("fam").min_res.mean().round(2).to_dict())
print("\nFER5 corse per linea:",tr[tr.service_id=="FER5_INV_2627"].route_short_name.value_counts().to_dict())
print("FER6 corse per linea:",tr[tr.service_id=="FER6_INV_2627"].route_short_name.value_counts().to_dict())
print("\nfermate non usate:",stops[~stops.stop_id.isin(st.stop_id)][["stop_id","stop_code","stop_name"]].values.tolist())
print("stop_code duplicato:",stops[stops.stop_code.duplicated(keep=False)&(stops.stop_code!="")][["stop_id","stop_code","stop_name"]].values.tolist())
d=stops[stops.duplicated(["stop_lat","stop_lon"],keep=False)].sort_values(["stop_lat","stop_lon"])
print("stesse coordinate:\n",d[["stop_id","stop_name","stop_lat"]].to_string(index=False))
